# gen_tables.py  -  writes sketches/w11_tables.cpp: the synthetic dense-layer weights that
#                   every board in the room uses, as `const` arrays so they live in FLASH.
#
# Usage:  python scripts/gen_tables.py            (from the pack folder)
#
# Why synthetic: a trained model from one laptop would differ from the next, and then a
# difference in two students' numbers could be the model instead of the memory. With a
# fixed seed every board holds byte-identical weights, so a difference can only be WHERE
# the bytes live and HOW WIDE they are. Same reasoning as W07's synthetic wave.
#
# The sketch checks the table against W11_W_F32_SUM below before it times anything, so a
# table that was edited, truncated, or regenerated with another seed is refused, not used.
#
# Standard library only. Deterministic: run it twice, get the same file.
import os
import random
import struct

SEED = 1119            # 19 Nov, the day of the session
N_IN, N_OUT = 256, 128  # one dense layer: 32768 weights, 128 outputs
N_W = N_IN * N_OUT

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "sketches", "w11_tables.cpp")


def f32(x):
    """Round a Python float to the nearest float32 and give both the value and its bits."""
    bits = struct.unpack("<I", struct.pack("<f", x))[0]
    return struct.unpack("<f", struct.pack("<I", bits))[0], bits


def quantise(values):
    """Symmetric per-tensor int8: q = round(v / s), s = max|v| / 127. Returns (q list, s)."""
    amax = max(abs(v) for v in values)
    s, _ = f32(amax / 127.0)
    q = [max(-127, min(127, int(round(v / s)))) for v in values]
    return q, s


def main():
    rng = random.Random(SEED)
    w = [f32(rng.uniform(-1.0, 1.0))[0] for _ in range(N_W)]
    x = [f32(rng.uniform(-1.0, 1.0))[0] for _ in range(N_IN)]
    w_q, s_w = quantise(w)
    x_q, s_x = quantise(x)
    w_bits = [f32(v)[1] for v in w]
    x_bits = [f32(v)[1] for v in x]
    w_sum = sum(w_bits) & 0xFFFFFFFF            # wrapping uint32 sum, order-independent
    s8_sum = sum(w_q) & 0xFFFFFFFF

    def rows(items, fmt, per):
        out = []
        for i in range(0, len(items), per):
            out.append("  " + ", ".join(fmt % v for v in items[i:i + per]) + ",")
        return "\n".join(out)

    body = []
    body.append("// w11_tables.cpp - GENERATED by scripts/gen_tables.py (seed %d). Do not edit by hand." % SEED)
    body.append("// One dense layer, %d x %d, as const data so that it is placed in FLASH (.rodata)." % (N_IN, N_OUT))
    body.append("// Float weights are stored as their IEEE-754 bit patterns so the same table serves")
    body.append("// the word benchmark (as uint32) and the float kernel (as float) without a second copy.")
    body.append("#include <stdint.h>")
    body.append("#include \"w11_common.h\"")
    body.append("")
    body.append("const uint32_t W11_W_F32_SUM = 0x%08Xu;   // wrapping sum of all %d words, checked on the board" % (w_sum, N_W))
    body.append("const uint32_t W11_W_S8_SUM  = 0x%08Xu;   // wrapping sum of all %d int8 weights" % (s8_sum, N_W))
    body.append("const float    W11_SCALE_W   = %.9ef;" % s_w)
    body.append("const float    W11_SCALE_X   = %.9ef;" % s_x)
    body.append("")
    body.append("const uint32_t W11_W_F32_BITS[%d] = {" % N_W)
    body.append(rows(w_bits, "0x%08X", 8))
    body.append("};")
    body.append("")
    body.append("const int8_t W11_W_S8[%d] = {" % N_W)
    body.append(rows(w_q, "%4d", 16))
    body.append("};")
    body.append("")
    body.append("const uint32_t W11_X_F32_BITS[%d] = {" % N_IN)
    body.append(rows(x_bits, "0x%08X", 8))
    body.append("};")
    body.append("")
    body.append("const int8_t W11_X_S8[%d] = {" % N_IN)
    body.append(rows(x_q, "%4d", 16))
    body.append("};")
    body.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body))
    print("wrote %s" % os.path.normpath(OUT))
    print("  %d weights, scale_w = %.9e, scale_x = %.9e" % (N_W, s_w, s_x))
    print("  W11_W_F32_SUM = 0x%08X   W11_W_S8_SUM = 0x%08X" % (w_sum, s8_sum))
    print("  int8 weights span %d..%d" % (min(w_q), max(w_q)))


if __name__ == "__main__":
    main()
