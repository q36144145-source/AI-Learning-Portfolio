# w10lib.py  -  what every W10 script shares: the log format, the eight features, the
#               confusion matrix, and the reasons a thing is refused.
#
# The eight features are computed here in the same order, with the same definitions, as
# computeFeatures() in sketches/w10_imu.h. If you change one, change the other.
#
# Requires numpy (you installed it for W03). Nothing else.
import hashlib
import json
import os
import re
import sys

import numpy as np

FS_HZ = 100
WIN_SAMPLES = 200
CLASSES = ["still", "tilt", "shake", "tap"]           # index order fixed with w10_imu.h
FEAT_NAMES = ["amag_mean", "amag_std", "amag_max", "amag_min",
              "gmag_mean", "gmag_max", "az_std", "amag_zc"]
MIN_TRAIN_PER_CLASS = 6
MIN_TEST_PER_CLASS = 5
G0 = 9.80665                                           # m/s2 per g, for the Edge Impulse export


class Refused(Exception):
    """Raised with a one-paragraph reason whenever a result must not be produced."""


# ----------------------------------------------------------------------------- parsing

def file_hash(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def parse_log(path, allow_synthetic=False):
    """Read one session log from sketch_a_collect.cpp.

    Returns dict(meta=..., windows=[...], dropped=[(id, label, reason), ...]).
    Each window: id, label, rows (ndarray WIN_SAMPLES x 6: ax ay az gx gy gz),
    ticks, missed, clipped, read_failed.

    Refuses (raises Refused) when the file is not a complete W10 collect log, when the
    board halted before logging, when the source is synthetic and that was not allowed,
    or when no usable window survives. Drops - but does not refuse on - individual
    windows that are cut, short, missed a tick, clipped, or failed a read; those are
    returned in `dropped` with the reason so that you can write the count down.
    """
    if not os.path.isfile(path):
        raise Refused("no file at %r." % path)
    meta, windows, dropped = {}, [], []
    cur = None
    is_collect = False
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("halt="):
                raise Refused("the board printed %r before logging anything. A halt line means "
                              "the sketch refused to run; nothing in this file is data. Fix the "
                              "cause it names and record the session again." % line)
            if line.startswith("#"):
                if "W10 collect" in line:
                    is_collect = True
                for k, v in re.findall(r"(\w+)=([^\s]+)", line):
                    meta.setdefault(k, v)
                continue
            if line.startswith(">>"):
                continue                                   # the prompts
            m = re.match(r"^W (\d+) (\w+) begin$", line)
            if m:
                if cur is not None:
                    dropped.append((cur["id"], cur["label"], "cut: next window began before this one ended"))
                cur = {"id": int(m.group(1)), "label": m.group(2), "rows": []}
                continue
            m = re.match(r"^W (\d+) (\w+) end ticks=(\d+) missed=(\d+) clipped=(\d+) read_failed=(\d+)$", line)
            if m:
                if cur is None or cur["id"] != int(m.group(1)):
                    dropped.append((int(m.group(1)), m.group(2), "end marker without a begin"))
                    cur = None
                    continue
                cur["ticks"], cur["missed"], cur["clipped"], cur["read_failed"] = (int(m.group(i)) for i in (3, 4, 5, 6))
                _finish(cur, windows, dropped)
                cur = None
                continue
            if cur is not None:
                parts = line.split(",")
                if len(parts) == 7:
                    try:
                        cur["rows"].append([float(x) for x in parts[1:]])
                    except ValueError:
                        cur.setdefault("garbled", 0)
                        cur["garbled"] += 1
    if cur is not None:
        dropped.append((cur["id"], cur["label"], "cut: the file ended inside this window"))
    if not is_collect:
        raise Refused("%s is not a W10 collect log: no '# W10 collect' header. Is this the "
                      "classify sketch's log, or a W06 file?" % path)
    src = meta.get("source", "?")
    if src.upper() == "SYNTHETIC" and not allow_synthetic:
        raise Refused("%s was generated by selftest.py (source=SYNTHETIC). It is not data from "
                      "a sensor and this script will not train on it, tabulate it or export it "
                      "unless you say --selftest. Record a session on your board." % path)
    if src.upper() != "SYNTHETIC" and src != "mpu6050":
        raise Refused("%s says source=%s; this pack's sketches only write mpu6050 logs." % (path, src))
    for k, want in (("fs_hz", FS_HZ), ("window_samples", WIN_SAMPLES)):
        if k not in meta:
            raise Refused("%s has no %s in its header. The header is printed by w10_imu.h; "
                          "if it is missing, the monitor attached late. Record again." % (path, k))
        if int(meta[k]) != want:
            raise Refused("%s was logged at %s=%s but this pack expects %d. The sketch and the "
                          "scripts do not agree, so nothing here can be compared." % (path, k, meta[k], want))
    if not windows:
        raise Refused("no usable window in %s: %d were dropped (%s). Nothing to work with."
                      % (path, len(dropped), _reasons(dropped)))
    return {"meta": meta, "windows": windows, "dropped": dropped, "path": path,
            "stem": os.path.splitext(os.path.basename(path))[0], "hash": file_hash(path)}


def _finish(cur, windows, dropped):
    wid, label = cur["id"], cur["label"]
    n = len(cur["rows"])
    if label not in CLASSES:
        dropped.append((wid, label, "label %r is not one of %s" % (label, CLASSES))); return
    if cur.get("garbled"):
        dropped.append((wid, label, "%d garbled rows" % cur["garbled"])); return
    if n != WIN_SAMPLES:
        dropped.append((wid, label, "%d rows, expected %d" % (n, WIN_SAMPLES))); return
    if cur["missed"]:
        dropped.append((wid, label, "missed %d tick(s): the time axis is broken" % cur["missed"])); return
    if cur["clipped"]:
        dropped.append((wid, label, "%d sample(s) at full scale: the peak is not the peak" % cur["clipped"])); return
    if cur["read_failed"]:
        dropped.append((wid, label, "%d failed read(s)" % cur["read_failed"])); return
    rows = np.array(cur["rows"], dtype=np.float64)
    windows.append({"id": wid, "label": label, "y": CLASSES.index(label), "rows": rows,
                    "ticks": cur["ticks"], "missed": 0, "clipped": 0, "read_failed": 0,
                    "rowhash": hashlib.sha256(rows.tobytes()).hexdigest()[:16]})


def _reasons(dropped):
    seen = {}
    for _, _, r in dropped:
        key = r.split(":")[0]
        seen[key] = seen.get(key, 0) + 1
    return ", ".join("%s x%d" % (k, v) for k, v in seen.items()) or "none"


# ----------------------------------------------------------------------------- features

def features(rows):
    """The eight features of one window, in FEAT_NAMES order. Same maths as w10_imu.h."""
    a = rows[:, 0:3]
    g = rows[:, 3:6]
    amag = np.sqrt((a * a).sum(axis=1))
    gmag = np.sqrt((g * g).sum(axis=1))
    d = amag - amag.mean()
    s = d < 0
    zc = int((s[1:] != s[:-1]).sum())
    return np.array([amag.mean(), amag.std(), amag.max(), amag.min(),
                     gmag.mean(), gmag.max(), rows[:, 2].std(), float(zc)])


def feature_matrix(windows):
    X = np.array([features(w["rows"]) for w in windows])
    y = np.array([w["y"] for w in windows])
    ids = [w["id"] for w in windows]
    return X, y, ids


def class_counts(windows):
    c = {k: 0 for k in CLASSES}
    for w in windows:
        c[w["label"]] += 1
    return c


def require_min(counts, minimum, what):
    short = [k for k in CLASSES if counts[k] < minimum]
    if short:
        raise Refused("the %s set has too few windows for %s: %s. The minimum is %d per class. "
                      "A confusion matrix row built on fewer than that moves in steps too coarse "
                      "to read, and this script will not print one. Record the missing windows "
                      "(or check why they were dropped) and run again."
                      % (what, ", ".join(short), ", ".join("%s=%d" % (k, counts[k]) for k in short), minimum))


def feature_table(X, y):
    """Per class, per feature: min / median / max. From the TRAINING set only."""
    lines = []
    lines.append("feature        " + "".join("%-26s" % c for c in CLASSES))
    lines.append("               " + "".join("%-26s" % "min   median   max" for _ in CLASSES))
    for j, name in enumerate(FEAT_NAMES):
        row = "%-14s " % name
        for c in range(len(CLASSES)):
            v = X[y == c, j]
            if len(v) == 0:
                row += "%-26s" % "(no windows)"
            else:
                row += "%-26s" % ("%7.3f %7.3f %7.3f" % (v.min(), np.median(v), v.max()))
        lines.append(row)
    return "\n".join(lines)


# ----------------------------------------------------------------------------- confusion

def confusion(y_true, y_pred):
    cm = np.zeros((len(CLASSES), len(CLASSES)), dtype=int)
    for t, p in zip(y_true, y_pred):
        cm[t, p] += 1
    return cm


def metrics(cm):
    """Per-class precision and recall (None where the denominator is 0), accuracy,
    and the accuracy of a model that always says the commonest class."""
    out = {"precision": [], "recall": [], "n_true": [], "n_pred": []}
    for c in range(len(CLASSES)):
        tp = int(cm[c, c]); nt = int(cm[c, :].sum()); npred = int(cm[:, c].sum())
        out["n_true"].append(nt); out["n_pred"].append(npred)
        out["recall"].append(tp / nt if nt else None)
        out["precision"].append(tp / npred if npred else None)
    total = int(cm.sum())
    out["accuracy"] = int(np.trace(cm)) / total if total else None
    out["majority_accuracy"] = int(cm.sum(axis=1).max()) / total if total else None
    out["total"] = total
    return out


def format_cm(cm, title):
    m = metrics(cm)
    w = max(6, max(len(c) for c in CLASSES) + 1)
    lines = [title, "  rows = what you did, columns = what it said   (n = %d windows)" % m["total"], ""]
    lines.append("  %-*s" % (w, "") + "".join("%*s" % (w, c) for c in CLASSES) + "   recall   (granularity)")
    for i, c in enumerate(CLASSES):
        r = m["recall"][i]
        rs = "   n/a  " if r is None else " %6.1f%%" % (100 * r)
        gran = "" if not m["n_true"][i] else "  (1/%d = %.0f pts)" % (m["n_true"][i], 100.0 / m["n_true"][i])
        lines.append("  %-*s" % (w, c) + "".join("%*d" % (w, cm[i, j]) for j in range(len(CLASSES))) + rs + gran)
    pr = "  %-*s" % (w, "precision")
    for j in range(len(CLASSES)):
        p = m["precision"][j]
        pr += "%*s" % (w, "n/a" if p is None else "%.0f%%" % (100 * p))
    lines.append(pr)
    lines.append("")
    missing = [CLASSES[i] for i in range(len(CLASSES)) if m["n_true"][i] == 0]
    if missing:
        lines.append("  overall accuracy: NOT REPORTED - no test windows for %s, so a single number "
                     "would be about the other classes only." % ", ".join(missing))
    else:
        lines.append("  overall accuracy        %.1f%%" % (100 * m["accuracy"]))
        lines.append("  always-'%s' baseline  %.1f%%   <- a model that never looks at the data scores this"
                     % (CLASSES[int(np.argmax(cm.sum(axis=1)))], 100 * m["majority_accuracy"]))
    worst = worst_cell(cm)
    if worst:
        lines.append("  largest off-diagonal cell: did %s, said %s, %d time(s)" % worst)
    return "\n".join(lines)


def worst_cell(cm):
    best = None
    for i in range(len(CLASSES)):
        for j in range(len(CLASSES)):
            if i != j and cm[i, j] > 0 and (best is None or cm[i, j] > best[2]):
                best = (CLASSES[i], CLASSES[j], int(cm[i, j]))
    return best


def write_cm(path, name, cm, ids, extra=None):
    d = {"name": name, "classes": CLASSES, "cm": [[int(v) for v in row] for row in cm.tolist()],
         "test_ids": [int(i) for i in ids]}
    if extra:
        d.update(extra)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(d, f, indent=1)


def read_cm(path):
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    return d["name"], np.array(d["cm"], dtype=int), d.get("test_ids", []), d


# ----------------------------------------------------------------------------- edge impulse

def ei_json(window, device_name, accel_only=False):
    """One window in the Edge Impulse data acquisition format (unsigned: alg none)."""
    rows = window["rows"]
    sensors = [{"name": "accX", "units": "m/s2"}, {"name": "accY", "units": "m/s2"}, {"name": "accZ", "units": "m/s2"}]
    if not accel_only:
        sensors += [{"name": "gyrX", "units": "dps"}, {"name": "gyrY", "units": "dps"}, {"name": "gyrZ", "units": "dps"}]
    values = []
    for r in rows:
        v = [round(float(r[0]) * G0, 4), round(float(r[1]) * G0, 4), round(float(r[2]) * G0, 4)]
        if not accel_only:
            v += [round(float(r[3]), 3), round(float(r[4]), 3), round(float(r[5]), 3)]
        values.append(v)
    return {
        "protected": {"ver": "v1", "alg": "none"},
        "signature": "0" * 64,
        "payload": {
            "device_name": device_name,
            "device_type": "ESP32-S3-DevKitC-1",
            "interval_ms": 1000.0 / FS_HZ,
            "sensors": sensors,
            "values": values,
        },
    }


def refused(e):
    print("REFUSED  %s" % e)
    return 2
